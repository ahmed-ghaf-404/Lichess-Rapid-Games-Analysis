function getInitialLocale() {
  const saved = window.localStorage.getItem(STORAGE_KEY);
  if (SUPPORTED_LOCALES.some(({ id }) => id === saved)) return saved;

  const browserLocale = window.navigator.language.toLowerCase();
  if (browserLocale.startsWith("ar")) return "ar";
  if (browserLocale.startsWith("ja")) return "ja";
  return "en";
}

function interpolate(message, values) {
  return Object.entries(values).reduce(
    (result, [name, value]) => result.replaceAll(`{${name}}`, String(value)),
    message
  );
}

export function LocalizationProvider({ children }) {
  const [locale, setLocale] = useState(getInitialLocale);
  const metadata = SUPPORTED_LOCALES.find(({ id }) => id === locale) || SUPPORTED_LOCALES[0];

  useEffect(() => {
    window.localStorage.setItem(STORAGE_KEY, locale);
    document.documentElement.lang = metadata.languageTag;
    document.documentElement.dir = metadata.direction;
    document.documentElement.dataset.locale = locale;
  }, [locale, metadata.direction, metadata.languageTag]);

  const t = useCallback(
    (key, values = {}) => {
      const message = MESSAGES[locale]?.[key] ?? MESSAGES.en[key] ?? key;
      return interpolate(message, values);
    },
    [locale]
  );

  const formatNumber = useCallback(
    (value, options) => new Intl.NumberFormat(metadata.languageTag, options).format(value),
    [metadata.languageTag]
  );

  const formatDate = useCallback(
    (value, options) => new Intl.DateTimeFormat(metadata.languageTag, options).format(value),
    [metadata.languageTag]
  );

  const value = useMemo(
    () => ({ locale, setLocale, metadata, t, formatNumber, formatDate }),
    [formatDate, formatNumber, locale, metadata, t]
  );

  return (
    <LocalizationContext.Provider value={value}>
      {children}
    </LocalizationContext.Provider>
  );
}
